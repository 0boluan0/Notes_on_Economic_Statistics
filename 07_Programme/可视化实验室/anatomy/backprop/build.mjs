import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import * as K from '../kit/iso-kit.mjs';

const here=path.dirname(fileURLToPath(import.meta.url));
const assets=path.resolve(here,'../../assets');
const q=Math.SQRT1_2;
const world=(u,v,z)=>[(u+v)*q,(v-u)*q,z];
const corners=(u,v,w,d,z)=>[[u,v],[u+w,v],[u+w,v+d],[u,v+d]].map(([x,y])=>world(x,y,z));
const P=K.fitProjection([...corners(-300,-80,600,160,-17),...corners(-300,-80,600,160,37)],1000,250,{pad:25,azimuth:39,elevation:36});
const at=(u,v,z)=>K.iso(world(u,v,z),P);
const pts=(u,v,w,d)=>corners(u,v,w,d,0).map(p=>p.slice(0,2));
let count=0;
const slab=(u,v,w,d,z,h,tone='mid',cls='')=>{count++;return K.solidSvg(K.extrude(pts(u,v,w,d),z,h,P,{bevel:.6}),{tone,className:cls});};
const line=(a,b,tone='lo',free=false)=>K.lineSvg(K.segment(world(...a),world(...b),P),{tone,free});
const dots=points=>K.dotsSvg(points.map(p=>at(...p)),{size:1,tone:'lo'});
const polygon=(u,v,w,d,z)=>corners(u,v,w,d,z).map(p=>K.iso(p,P).join(',')).join(' ');
const matrix=(u,v,z)=>{const p=at(u,v,z),a=at(u+1,v,z),b=at(u,v+1,z);return `matrix(${a[0]-p[0]} ${a[1]-p[1]} ${b[0]-p[0]} ${b[1]-p[1]} ${p[0]} ${p[1]})`;};
let base='';
for(const u of [-276,260])for(const v of [-64,50])base+=slab(u,v,18,18,-17,7,'lo');
base+=slab(-300,-80,600,160,-10,10,'lo');
for(const v of [-57,53])base+=slab(-280,v,560,5,0,5,'mid');
for(const u of [-286,278])base+=slab(u,-61,8,124,0,9,'mid');
base+=dots([[-291,-71,0],[291,-71,0],[-291,71,0],[291,71,0]]);
const nodes=['x','z','h','output','loss'];
const centers=[-224,-112,0,112,224];
for(let i=0;i<4;i++)base+=slab(centers[i]+42,-4,28,8,0,3,'lo');
base+=slab(-60,64,120,9,0,.8,'lo');
base+=`<text transform="${matrix(-50,71,.9)}" font-size="5" fill="currentColor">DIFFERENTIATION / 01</text>`;
const modules=nodes.map((id,i)=>{
  const u=centers[i];let body='';
  body+=slab(u-43,-52,86,108,5,5,'mid');
  body+=slab(u-39,-48,78,100,10,19,'mid');
  body+=slab(u-35,-44,70,92,29,2,'hi');
  body+=slab(u-31,-39,62,30,31,2,'mid');
  body+=slab(u-28,-36,56,24,33,.6,'lo');
  body+=slab(u-25,-4,5,42,31,1,'lo');
  body+=slab(u+20,-4,5,42,31,1,'lo');
  body+=slab(u-20,15,40,1,31,.25,'lo');
  body+=slab(u-10,-56,20,4,5,7,'mid');
  for(let y=0;y<=36;y+=6){body+=line([u-25,y,32],[u-21,y,32]);body+=line([u+21,y,32],[u+25,y,32]);}
  body+=dots([[u-32,-41,31],[u+32,-41,31],[u-32,44,31],[u+32,44,31]]);
  const railVector=[at(u,1,32)[0]-at(u,0,32)[0],at(u,1,32)[1]-at(u,0,32)[1]];
  const slider=slab(u-18,13,36,5,31.3,3,'hi')+slab(u-8,13.5,16,4,34.3,2,'hi');
  const center=at(u,-23,34);
  body+=`<g data-bp-carriage="${id}">${slider}</g>`;
  body+=`<text data-bp-display="${id}" x="${center[0]}" y="${center[1]+4}" text-anchor="middle" font-size="16" font-family="ui-monospace,monospace" fill="currentColor">—</text>`;
  body+=`<polygon points="${polygon(u-39,-48,78,100,31)}" class="bp-machine-hit" data-bp-node="${id}" tabindex="0" role="button" aria-label="查看 ${['输入 x','线性组合 z','隐藏值 h','预测 y','损失 L'][i]}"/>`;
  return {id,body,vector:railVector,center:at(u,56,8)};
});
const svg=K.figureSvg({width:1000,height:250,label:'五个可检查的运算盒：输入、乘加、tanh、输出乘法、平方损失。滑块表示当前值在各自刻度内的位置。',body:base+modules.map(x=>`<g class="bp-machine-module" data-bp-module="${x.id}">${x.body}</g>`).join('')});
fs.writeFileSync(path.join(assets,'story-backprop-01-geometry.js'),`/* Generated by anatomy/backprop/build.mjs; Anatomy MIT. */\nglobalThis.BackpropInstrument=${JSON.stringify({svg,modules:modules.map(({id,vector,center})=>({id,vector,center})),parts:count})};\n`);
fs.writeFileSync(path.join(assets,'story-backprop-01-geometry.css'),K.ISO_CSS.replaceAll('.iso','.bp-anatomy .iso').replaceAll('.bp-anatomy .iso{','.bp-anatomy{').replaceAll('.bp-anatomy .iso[data-theme="light"]','.bp-anatomy[data-theme="light"]'));
console.log(JSON.stringify({parts:count,output:'assets/story-backprop-01-geometry.js'}));
